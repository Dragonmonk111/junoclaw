import { readFileSync, existsSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'
import { DirectSecp256k1HdWallet } from '@cosmjs/proto-signing'
import { SigningCosmWasmClient } from '@cosmjs/cosmwasm-stargate'
import { GasPrice } from '@cosmjs/stargate'
import { randomBytes } from 'crypto'

const __dir = dirname(fileURLToPath(import.meta.url))

// ── Config ──────────────────────────────────────────────────────────────────

const CHAIN_ID  = process.env.CHAIN_ID  || 'uni-7'
const RPC_URL   = process.env.RPC_URL   || 'https://juno-testnet-rpc.polkachu.com'
const GAS_PRICE = process.env.GAS_PRICE || '0.075ujunox'

const DEPLOYED_FILE = join(__dir, 'deployed-testnet.json')

function loadMnemonic() {
  if (process.env.MNEMONIC) return process.env.MNEMONIC
  console.error('Set MNEMONIC env var (deployer wallet).')
  process.exit(1)
}

function loadDeployed() {
  if (existsSync(DEPLOYED_FILE)) {
    return JSON.parse(readFileSync(DEPLOYED_FILE, 'utf8'))
  }
  return {}
}

// ── Jolt Proof Generation (demo) ─────────────────────────────────────────────
//
// In a real deployment, the Jolt proof is generated off-chain using the
// Jolt prover crate. The prover:
//   1. Compiles the guest program to RISC-V bytecode
//   2. Runs the program on the given inputs
//   3. Generates a JoltProof struct (protocol config + commitments + sumcheck claims)
//   4. Serializes the proof via bincode
//   5. Base64-encodes for on-chain submission
//
// For this demo, we generate a structurally-valid proof blob that passes
// the jolt-cw-verifier's Phase 1 structural validation. A real proof would
// be generated by:
//
//   ```rust
//   use jolt::JoltProof;
//   let proof = JoltProof::prove(program, inputs);
//   let proof_bytes = bincode::serialize(&proof).unwrap();
//   let proof_b64 = base64::encode(&proof_bytes);
//   ```
//
// The proof blob format:
//   - First 4 bytes: "JOLT" magic (or bincode preamble: 0x00/0x01)
//   - Remaining: serialized protocol config + commitments + sumcheck claims
//   - Typical size: 65-80KB for a simple program

function generateDemoProof() {
  // Create a structurally valid Jolt proof blob for Phase 1 validation
  // Phase 1 checks: non-empty, <= 512KB, magic bytes (JOLT or bincode 0x00/0x01)
  
  const magic = Buffer.from('JOLT', 'ascii')
  // Pad with deterministic data to simulate a real proof (~2KB for demo)
  // Real Jolt proofs are 65-80KB; we keep this small for gas efficiency in testing
  const body = randomBytes(2048)
  // Make first byte of body 0x01 (bincode "Some" variant tag) to satisfy structural check
  body[0] = 0x01
  
  return Buffer.concat([magic, body])
}

function generateRealProofInstructions() {
  return `
  ── Real Jolt Proof Generation ──────────────────────────────────
  
  To generate a REAL Jolt ZK proof (not the demo blob above):
  
  1. Install the Jolt toolkit:
     cargo install jolt-cli
  
  2. Write a guest program (e.g., prove a computation):
     // guest.rs
     fn fibonacci(n: u64) -> u64 {
         if n <= 1 { return n; }
         let mut a = 0u64;
         let mut b = 1u64;
         for _ in 0..n-1 {
             let c = a + b;
             a = b;
             b = c;
         }
         b
     }
  
  3. Generate the proof:
     jolt prove --program guest.rs --input "42"
  
  4. The output is a bincode-serialized JoltProof.
     Base64-encode it for on-chain submission:
     base64 proof.bin > proof.b64
  
  5. Submit to jolt-cw-verifier:
     junod tx wasm execute <verifier-addr> \\
       '{"store_proof": {"proof_base64": "<b64>", "program_hash": "sha256:abc..."}}' \\
       --from <wallet> --chain-id ${CHAIN_ID} --node ${RPC_URL}
  
  6. Verify the stored proof:
     junod tx wasm execute <verifier-addr> \\
       '{"verify_proof": {"proof_base64": null}}' \\
       --from <wallet> --chain-id ${CHAIN_ID} --node ${RPC_URL}
  
  7. Query proof status:
     junod query wasm contract-state smart <verifier-addr> \\
       '{"proof_status": {}}' --node ${RPC_URL}
  `
}

// ── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log('\n  === End-to-End Jolt Proof Example ===')
  console.log(`  Chain:    ${CHAIN_ID}`)
  console.log(`  RPC:      ${RPC_URL}\n`)

  const mnemonic = loadMnemonic()
  const wallet = await DirectSecp256k1HdWallet.fromMnemonic(mnemonic, { prefix: 'juno' })
  const [{ address }] = await wallet.getAccounts()
  console.log(`  Wallet:   ${address}`)

  const client = await SigningCosmWasmClient.connectWithSigner(RPC_URL, wallet, {
    gasPrice: GasPrice.fromString(GAS_PRICE),
  })

  const balance = await client.getBalance(address, 'ujunox')
  console.log(`  Balance:  ${(BigInt(balance.amount) / 1_000_000n).toString()} JUNOX\n`)

  const deployed = loadDeployed()

  // ── Check jolt-cw-verifier is deployed ──────────────────────────────────────

  const verifierAddr = process.env.JOLT_VERIFIER || deployed['jolt-cw-verifier']?.address
  if (!verifierAddr) {
    console.error('  ❌ jolt-cw-verifier not deployed. Run deploy-jolt-verifier-testnet.mjs first.')
    process.exit(1)
  }
  console.log(`  Verifier: ${verifierAddr}\n`)

  // ── Step 1: Generate proof ──────────────────────────────────────────────────

  console.log('  ── Step 1: Generate Jolt proof ────────────────────────────')
  
  const useRealProof = process.env.JOLT_PROOF_B64
  let proofB64

  if (useRealProof) {
    console.log('  Using real proof from JOLT_PROOF_B64 env var')
    proofB64 = useRealProof
  } else {
    console.log('  Generating demo proof blob (Phase 1 structural validation)...')
    console.log('  (Set JOLT_PROOF_B64 env var to use a real Jolt proof)')
    const proofBlob = generateDemoProof()
    proofB64 = proofBlob.toString('base64')
  }
  
  console.log(`  Proof size: ${(proofB64.length * 3 / 4 / 1024).toFixed(1)} KB (base64: ${proofB64.length} chars)`)

  // ── Step 2: Store proof on-chain ────────────────────────────────────────────

  console.log('\n  ── Step 2: Store proof on-chain ────────────────────────────')
  
  const programHash = process.env.PROGRAM_HASH || null
  
  const storeMsg = {
    store_proof: {
      proof_base64: proofB64,
      program_hash: programHash,
    },
  }

  console.log(`  Storing proof to ${verifierAddr}...`)
  const storeResult = await client.execute(
    address,
    verifierAddr,
    storeMsg,
    'auto',
    'Store Jolt proof (e2e demo)'
  )
  console.log(`  ✅ Proof stored!  tx: ${storeResult.transactionHash}`)
  
  // Parse events for proof hash
  for (const evt of storeResult.events) {
    if (evt.type === 'wasm-store_proof' || evt.attributes.some(a => a.key === 'action' && a.value === 'store_proof')) {
      for (const attr of evt.attributes) {
        if (attr.key === 'proof_sha256') {
          console.log(`     SHA256: ${attr.value}`)
        }
        if (attr.key === 'proof_size_bytes') {
          console.log(`     Size:   ${attr.value} bytes`)
        }
      }
    }
  }

  // ── Step 3: Verify proof on-chain ───────────────────────────────────────────

  console.log('\n  ── Step 3: Verify proof on-chain ────────────────────────────')
  
  const verifyMsg = {
    verify_proof: {
      proof_base64: proofB64,
    },
  }

  console.log(`  Verifying proof on ${verifierAddr}...`)
  const verifyResult = await client.execute(
    address,
    verifierAddr,
    verifyMsg,
    'auto',
    'Verify Jolt proof (e2e demo)'
  )
  console.log(`  ✅ Verification submitted!  tx: ${verifyResult.transactionHash}`)

  // Parse verification result from events
  for (const evt of verifyResult.events) {
    for (const attr of evt.attributes) {
      if (attr.key === 'verified') {
        console.log(`     Verified: ${attr.value}`)
      }
      if (attr.key === 'verify_mode') {
        console.log(`     Mode:     ${attr.value}`)
      }
      if (attr.key === 'block_height') {
        console.log(`     Block:    ${attr.value}`)
      }
      if (attr.key === 'note') {
        console.log(`     Note:     ${attr.value}`)
      }
    }
  }

  // ── Step 4: Query proof status ─────────────────────────────────────────────

  console.log('\n  ── Step 4: Query proof status ──────────────────────────────')
  
  const status = await client.queryContractSmart(verifierAddr, { proof_status: {} })
  console.log(`  Has proof:         ${status.has_proof}`)
  console.log(`  Proof size:        ${status.proof_size_bytes} bytes`)
  console.log(`  Program hash:      ${status.program_hash || 'none'}`)
  console.log(`  Proof SHA256:      ${status.proof_sha256 || 'none'}`)
  console.log(`  Last verify:       ${status.last_verify_verified}`)
  console.log(`  Last verify block: ${status.last_verify_block}`)
  console.log(`  Verifier mode:     ${status.verifier_mode || 'structural (default)'}`)

  // ── Step 5: If ibc-task-host is deployed, forward proof via IBC ─────────────

  const taskHostAddr = process.env.IBC_TASK_HOST || deployed['ibc-task-host']?.address
  if (taskHostAddr) {
    console.log('\n  ── Step 5: Forward proof via ibc-task-host ────────────────')
    console.log(`  Task host: ${taskHostAddr}`)
    
    // Check if jolt_verifier is wired
    const hostConfig = await client.queryContractSmart(taskHostAddr, { config: {} })
    console.log(`  Host jolt_verifier: ${hostConfig.jolt_verifier || 'not configured'}`)
    
    if (hostConfig.jolt_verifier) {
      console.log('  (IBC proof forwarding would happen via ICS-20+PFM memo from counterparty chain)')
      console.log('  The ibc-task-host would receive SubmitProof via IBC and dispatch to jolt_verifier.')
    }
  }

  // ── Summary ────────────────────────────────────────────────────────────────

  console.log('\n  ═══════════════════════════════════════════════════════')
  console.log('  ✅ End-to-End Jolt Proof Example Complete!')
  console.log(`     Verifier:  ${verifierAddr}`)
  console.log(`     Proof:     ${proofB64.length} chars (base64)`)
  console.log(`     Verified:  ${status.last_verify_verified}`)
  console.log(`     Block:     ${status.last_verify_block}`)
  console.log('  ═══════════════════════════════════════════════════════')

  if (!useRealProof) {
    console.log(generateRealProofInstructions())
  }
}

main().catch((err) => {
  console.error('\n  ❌ E2E example failed:', err.message || err)
  if (err.stack) console.error(err.stack)
  process.exit(1)
})
